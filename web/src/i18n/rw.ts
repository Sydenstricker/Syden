//
// PLURAL — o que exige cuidado: a língua tem classes nominais, e o PREFIXO muda entre um e muitos
// (umuntu/abantu, umuyoboro/imiyoboro, ihuriro/amahuriro), arrastando junto adjetivo e verbo. Um {n}
