// TOM: o quiniaruanda tem o "vocês"/plural de respeito (mu-, mwe), e o Syden usa o singular direto
// (u-/wowe): "Hitamo", "Ufite konti?", "Urakaza neza" (e não "Murakaza neza"). Os botões vão no
// imperativo puro, como no MediaWiki ("Siba", "Bika", "Ohereza").
//
// GÊNERO: NÃO HÁ. "We"/"yo" é ele e ela, e verbo e adjetivo não mudam pelo sexo. A releitura de gênero
