// "Mu ihamagara ubu: {n}". As chaves que já vêm separadas para 1 ("1 mensagem") levam o singular.
// Nas frases em que o número é certamente maior que 1 ("193 países", "15 membros") vai o plural.
//
// O {campo} NO MEIO DA FRASE: a concordância depende da classe do nome, e um {nome} não tem classe
