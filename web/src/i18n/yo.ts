//
// A chave é o TEXTO EM PORTUGUÊS, exatamente como aparece no código. O que faltar aqui aparece em
// português, e não como tela vazia.
//
// ---------------------------------------------------------------------------------------------------
// A PERGUNTA DE SEMPRE — "ONDE ESTA LÍNGUA ESCONDE O GÊNERO?" — AQUI TEM A RESPOSTA FÁCIL: EM LUGAR
// NENHUM.
//
// O iorubá não marca sexo em pronome: **ó** serve para ele, ela e aquilo, e **wọn** para eles e elas.
// Depois de três línguas seguidas em que o gênero era o problema central (hauçá em quem lê, tailandês
// em quem fala, amárico em quem lê de novo), esta é a primeira em que ele simplesmente não existe.
// Vale registrar pelo contraste: a pergunta continua valendo para toda língua nova, e às vezes a
// resposta é "não esconde em parte nenhuma".
//
// O QUE ESTA LÍNGUA ESCONDE É OUTRA COISA: O RESPEITO. O iorubá separa **o / ìwọ** (a uma pessoa, com
// intimidade) de **ẹ / ẹ̀yin** (plural, e também a quem se respeita). Pela regra do Syden — tratar por
// "você", `du` e não `Sie` — a escolha seria `o`. **Aqui ela foi contrariada de propósito**, e o motivo
// é que a equivalência não vale: `o` para um adulto que você não conhece não é informalidade simpática,
// é falta de educação, de um jeito que `tu` no francês não é. Toda interface séria em iorubá usa `ẹ`.
//
// E NÃO É EXCEÇÃO INVENTADA PARA ESTA LÍNGUA: o hauçá já tinha ido para `ku`, a segunda pessoa do
// plural, e o amárico para እርስዎ. Os três chegaram à forma plural de respeito por caminhos diferentes.
// ---------------------------------------------------------------------------------------------------
//
// OS SINAIS NÃO SÃO ENFEITE, SÃO LETRAS DIFERENTES. O iorubá tem ẹ, ọ e ṣ — com ponto embaixo — que
// são letras próprias do alfabeto, e três tons marcados por acento: alto (á), baixo (à) e médio (sem
// marca). Tirar os sinais troca a palavra: `ọkọ̀` é veículo, `ọkọ` é marido, `oko` é fazenda. Escrever
// iorubá sem eles é o equivalente a escrever português sem nenhum acento e sem cedilha — dá para
// adivinhar, e está errado.
//
// FONTE: escrita latina, então a do Syden desenha quase tudo; ẹ, ọ e ṣ moram no bloco Latin Extended
// Additional, e a Noto Sans os cobre quando a fonte principal não cobrir.
//
// POR ISSO ELE ENTRA NO DETECTOR POR CHAVES de e2e/configuracoes-traduzidas.mjs, junto do vietnamita e
// do hauçá: em alfabeto latino não dá para dizer "sobrou português" procurando letra estranha, porque
// as letras são as mesmas. À, á, è, é, ì, í, ò, ó, ù e ú existem nas duas línguas. O que o iorubá NÃO
// tem é ã, õ, â, ê, ô e ç — e é por aí que o teste separa um do outro.
//
// MEDIDO, não suposto, com `node -e` antes de traduzir:
//
//   Intl.NumberFormat('yo').format(1234567.5)  ->  1,234,567.5   (algarismos latinos, vírgula e ponto)
//   Intl.PluralRules('yo')  ->  "other" para 0, 1, 2 e 5
//   Intl.DisplayNames('yo', region)  ->  NG = Nàìjíríà, BR = Bàràsílì, PT = Pọ́túgà
//   Intl.RelativeTimeFormat('yo')  ->  -1 dia = Àná
//
