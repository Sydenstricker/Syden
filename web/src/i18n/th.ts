// th — ไทย (tailandês).
//
// A chave é o TEXTO EM PORTUGUÊS, exatamente como aparece no código. O que faltar aqui aparece em
// português, e não como tela vazia.
//
// ---------------------------------------------------------------------------------------------------
// O ESPAÇO NÃO SEPARA PALAVRA — ELE SEPARA FRASE.
//
// Esta é a primeira língua do Syden em que o espaço mudou de função. Em tailandês as palavras se
// escrevem coladas (ตั้งรหัสผ่านใหม่ são quatro palavras) e o espaço faz o trabalho que a vírgula
// faz em português: separa oração de oração, destaca um número, isola uma palavra estrangeira.
//
// DUAS CONSEQUÊNCIAS PRÁTICAS, e as duas são erro fácil de cometer:
//   1. **Pôr espaço entre palavras tailandesas é erro de ortografia**, do mesmo tamanho que escrever
//      "a casa" como "a c a s a". Quem traduz vindo do português tem a mão viciada nisso.
//   2. **A vírgula do português vira espaço, e o ponto final vira nada.** O tailandês não termina
//      frase com ponto. Por isso quase nenhum valor deste arquivo tem "." no fim, embora a chave
//      tenha — não é descuido.
//
// QUEBRA DE LINHA: quem decide onde partir é o navegador, e não o espaço. Eu ia escrever aqui que
// isso depende de o elemento declarar `lang="th"` — MEDI, E NÃO DEPENDE. A mesma frase na mesma
// caixa, com `lang="th"`, sem lang nenhum e com `lang="en"`, quebra exatamente nos mesmos pontos
// no Chrome: ele reconhece a escrita pelos próprios caracteres. (O `<html lang>` continua sendo
// escrito por i18n/index.ts, e serve a leitor de tela e a seleção de fonte — só não é ele que
// manda na quebra.)
//
// E O `overflow-wrap: break-word` DO `body`, que o tâmil obrigou a pôr, NÃO ESTRAGA O TAILANDÊS.
// Era o risco real: em tailandês há sinais que nunca podem abrir linha (os de cima e os de baixo
// da consoante, U+0E31, U+0E34-3A, U+0E47-4E), e uma quebra arbitrária os arrancaria da base.
// Medido em caixa de 200, 120, 70 e até 40 px, e também com `word-break: break-all` forçado:
// ZERO linhas começando com um desses sinais. O Chrome agrupa a sílaba antes de quebrar.
// ---------------------------------------------------------------------------------------------------
//
// TRATAMENTO: o tailandês não escolhe entre "você" e "senhor" com um pronome, escolhe com as
// PARTÍCULAS DE FINAL DE FRASE — e elas dizem o sexo de QUEM FALA: ครับ se for homem, ค่ะ se for
// mulher. O Syden não tem sexo, então usar qualquer uma seria inventar um. **Não entra nenhuma**,
// que é exatamente o que as interfaces em tailandês fazem. O "você" é `คุณ`, que é o neutro de
// todo dia; `ท่าน` seria o "senhor" e fica de fora. E, como em tailandês o pronome se omite
// quando o contexto basta, boa parte das frases simplesmente não tem "você" nenhum.
//
// É o mesmo problema do hauçá por outro lado: lá o sexo estava em quem LÊ, aqui está em quem FALA.
//
// ALGARISMOS, medidos e não supostos: `Intl.NumberFormat('th').format(1234567)` devolve
// `1,234,567` — latinos, vírgula de milhar. Os algarismos tailandeses (๐๑๒๓๔๕๖๗๘๙) existem, mas
// hoje só aparecem em documento oficial e em contexto solene; na tela de um aplicativo seriam
// afetação. Os números deste arquivo vão com 0-9.
//
// E UMA QUE O INTL RESOLVE SOZINHO: `Intl.PluralRules('th')` só tem a categoria "other" — o
// tailandês não marca plural. "1 ข้อความ" e "5 ข้อความ" usam a mesma palavra, e as duas chaves do
// português ("1 mensagem" e "{n} mensagens") caem na mesma forma. É esperado, não é descuido.
//
