// A chave é o TEXTO EM PORTUGUÊS, exatamente como aparece no código. O que faltar aqui aparece em
// português, e não como tela vazia.
//
// ---------------------------------------------------------------------------------------------------
// A PERGUNTA DE SEMPRE — "ONDE ESTA LÍNGUA ESCONDE O GÊNERO?" — AQUI TEM UMA RESPOSTA NOVA: NO
// ADJETIVO QUE DESCREVE QUEM LÊ.
//
// O pronome grego não marca sexo na segunda pessoa (εσύ serve para todo mundo), mas o ADJETIVO e o
// PARTICÍPIO que se referem a quem lê marcam: "você está conectado" é συνδεδεμένος para um homem e
// συνδεδεμένη para uma mulher. O Syden não sabe o sexo de quem está lendo, e cada uma dessas frases
// erraria com metade das pessoas.
//
// A saída não é escolher um dos dois: é não precisar deles. Onde o português descreve a pessoa, este
// arquivo descreve a COISA ou a AÇÃO. "Senha alterada" (Ο κωδικός άλλαξε) em vez de "você alterou";
// "Μη έγκυρη συνεδρία" em vez de "você não está autenticado". Foi assim em toda frase que encostava
// no assunto.
//
// É a quarta língua seguida em que a pergunta rende: hauçá escondia o gênero em quem lê, tailandês em
// quem fala, amárico em quem lê, iorubá em lugar nenhum, e o grego em como se DESCREVE quem lê.
// ---------------------------------------------------------------------------------------------------
//
// O TRATAMENTO É εσύ, E AQUI A REGRA DO PROJETO VALE SEM RESSALVA. O grego separa εσύ (a uma pessoa)
// de εσείς (plural, e também cortesia), e a divisão é a mesma do tu/vous francês — não a do iorubá,
// onde a forma íntima soa grosseira. Entre amigos, εσείς soaria como repartição pública. Nos botões
// fica o imperativo singular (Διάλεξε, Στείλε, Σβήσε), que é como qualquer aplicativo grego fala.
//
// A INTERROGAÇÃO GREGA É O PONTO E VÍRGULA, e isso não é um defeito de codificação: "Τι έγινε;" é a
// forma correta de perguntar em grego. O ponto de interrogação latino (?) não existe nessa escrita,
// e usá-lo seria o mesmo que escrever português com o ponto final chinês. Vale a mesma decisão que o
// amárico tomou com ። — a pontuação faz parte da escrita.
//
// ACENTO: toda palavra grega de duas sílabas ou mais leva exatamente UM acento (τόνος), e ele muda a
// palavra. E o SIGMA TEM DUAS FORMAS: ς no fim da palavra, σ em qualquer outro lugar. Escrever
// "κωδικoσ" em vez de "κωδικός" é erro visível para quem lê.
//
// MEDIDO, não suposto, com `node -e` antes de traduzir:
//
//   Intl.NumberFormat('el').format(1234567.5)  ->  1.234.567,5   (ponto no milhar, vírgula no decimal)
//   Intl.PluralRules('el')  ->  1 = "one"; 0, 2, 5 e 11 = "other"
//   Intl.DisplayNames('el', region)  ->  GR = Ελλάδα, CY = Κύπρος, BR = Βραζιλία
//   Intl.RelativeTimeFormat('el')  ->  -1 dia = χθες
//
// A SEGUNDA LINHA SEPARA O GREGO DAS TRÊS ÚLTIMAS LÍNGUAS: ele TEM plural de verdade, com "one" e
// "other" distintos — ao contrário do tailandês e do iorubá, onde tudo era "other". As chaves do
// Syden já separam "1 mensagem" de "{n} mensagens", então as duas formas existem e estão certas.
//
