//
// ONDE O UCRANIANO ESCONDE O GÊNERO — o mesmo lugar do polonês, que veio antes:
//
//   1. no PASSADO: забув (homem) / забула (mulher) — "esqueceu a senha?";
//   2. no CONDICIONAL, que é o passado com "б": хотів би / хотіла б;
//   3. em ADJETIVO E PARTICÍPIO curto depois de "ser": впевнений / впевнена, вимкнений / вимкнена.
//
// A saída é a mesma: o PRESENTE e o FUTURO PERFECTIVO são neutros (маєш, можеш, втратиш), e a frase
// é reescrita para passar por eles. "Не пам’ятаєш пароль?" em vez de "забув"; "Мікрофон вимкнено"
// (forma impessoal em -но, que não tem sexo) em vez de "ти вимкнений"; "Точно видалити…?" em vez de
// "ти впевнений". As formas impessoais em -но/-то (створено, надіслано, змінено) são a ferramenta
// principal deste arquivo: elas dizem que aconteceu sem dizer quem.
//
// Os NOMES DE CARGO (Адміністратор, Власник, Учасник) ficam no masculino genérico, como em toda
// interface ucraniana — são rótulos de papel.
//
