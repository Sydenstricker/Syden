//
// A chave é o TEXTO EM PORTUGUÊS, exatamente como aparece no código. O que faltar aqui aparece em
// português, e não como tela vazia.
//
// ESCRITA: a latina, oficial desde 1993 e a que o navegador manda como "uz". O cirílico ainda circula
// (jornal, gente mais velha), mas misturar os dois numa tela é o erro a não cometer.
//
// TOM: **siz**, nunca *sen* — e aqui a escolha vai CONTRA o turco e o azerbaijano, que são parentes e
// usam o íntimo. No uzbeque o *sen* é de família e de amigo de infância; com quem acabou de chegar soa
// atrevido, e entre adultos que mal se conhecem o *siz* é o de amigo, não o de banco. É o mesmo padrão
// do malaio, do urdu, do persa e do japonês: a forma cortês é a neutra. O "senhor" de verdade seria
// *Siz* com maiúscula e *-lar* de respeito, e isso não entra.
//
// BOTÕES vão no substantivo verbal (Saqlash, Yuborish, Bekor qilish), que não tem pessoa nenhuma — é
// o que as interfaces uzbeques fazem. As FRASES que falam com a pessoa vão no *-ing* (yozing, tanlang).
//
// GÊNERO: NENHUM, como no turco e no azerbaijano — nem no "você", nem no "ele/ela" (u), nem no verbo.
//
// O ʻ E O ʼ SÃO LETRAS, NÃO ASPAS. Oʻ e gʻ se escrevem com U+02BB (ʻ), e a pausa glotal (taʼlim,
// maʼlumot) com U+02BC (ʼ). É a grafia oficial, e poupa este arquivo do apóstrofo ASCII, que dentro de
// '…' vira \' — foi assim que pares inteiros do hauçá sumiram da conferência sem aviso. NÃO "corrigir"
// para o ' do teclado.
//
// NOME PRÓPRIO COM SUFIXO vai com hífen (Syden-ga, Syden-da), como no azerbaijano. Campo {assim} NUNCA
// leva sufixo colado: o -ga vira -ka/-qa depois de k/q, e o nome que entra ali é desconhecido. Por isso
// "{nome} hamjamiyatida", com a palavra comum carregando o sufixo.
//
// NÚMEROS: o substantivo depois do número fica no singular e leva o contador *ta* ("5 ta xabar"). Com
// medida e unidade não vai *ta* ("5 soat", "10 kun"). `Intl.NumberFormat('uz')` devolve `1 234 567` —
// latinos, com espaço.
//
// O DETECTOR DO TESTE DE IDIOMAS: o uzbeque não escreve nenhum acento do português, mas é latino; vai o
// das chaves, que é a regra de toda língua latina.
//
