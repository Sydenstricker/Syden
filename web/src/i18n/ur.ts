// TOM: **آپ**, e isto NÃO é o "senhor" que o CLAUDE.md proíbe. Em urdu há duas formas de tratamento, e
// a escolha se parece com a do malaio, não com a do alemão: **تم** é de intimidade — entre irmãos, com
