//
// NÃO É O RUSSO. Divide o alfabeto e muita palavra emprestada, e copiar do ru.ts é o erro que passaria
// em todo teste: o cazaque tem nove letras próprias (ә ғ қ ң ө ұ ү һ і), é aglutinante, põe o verbo no
