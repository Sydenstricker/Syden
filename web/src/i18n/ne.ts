// A chave é o TEXTO EM PORTUGUÊS, exatamente como aparece no código. O que faltar aqui aparece em
// português, e não como tela vazia.
//
// NÃO É O HÍNDI. As duas línguas dividem a escrita e muita palavra, e copiar do hi.ts é o erro que
// passaria em todo teste: a grafia nepalesa é outra (सन्देश e não संदेश, च्यानल e não चैनल, सर्भर e
// não सर्वर, भिडियो e não वीडियो), o plural é -हरू, e o verbo não tem nada a ver.
//
// TOM: **तपाईं**, nunca *तिमी* — e aqui a escolha vai CONTRA o híndi do Syden, que usa o तुम. No
// nepalês o तिमी é de amigo antigo e de quem é mais novo; com quem acabou de chegar soa a quem se põe
// acima. O तपाईं é o neutro entre adultos, o de amigo que acabou de conhecer — e é o que Facebook e
// Google usam. O "senhor" de verdade seria हजुर, que não entra. Mesmo padrão do malaio, do urdu e do
// persa: a forma cortês é a neutra.
//
// GÊNERO: ESTÁ NO VERBO, e o honorífico o esconde. Com तिमी o passado marca o sexo de quem lê (गयौ /
// गएकी छौ); com तपाईं as formas são -नुभयो, -नुहुन्छ, -नुहोस्, que não têm sexo. A terceira pessoa
// também: उनी गइन् é mulher, उनी गए é homem — então quem não se sabe quem é vai no honorífico उहाँ
// (-नुभयो) ou numa frase em que o sujeito não aparece. Foi esse o motivo de fundo da escolha do tom.
//
// BOTÕES vão no imperativo honorífico (-नुहोस्: पठाउनुहोस्, खोल्नुहोस्), que é como as interfaces
// nepalesas escrevem, e que também não tem sexo.
//
// ALGARISMOS: o nepalês escreve ०१२३४५६७८९, e o Chrome não tem dados de número para ele — ver
