// O HEBRAICO ESCONDE O GÊNERO EM QUASE TODO LUGAR — E A ESCRITA SEM VOGAIS ABRE DUAS PORTAS.
//
// "Você" é אתה (homem) / את (mulher), e o verbo acompanha no PRESENTE (רואה/רואה com sufixos
// diferentes na fala, e רוצה/רוצה), no FUTURO (תשלח/תשלחי) e no IMPERATIVO (שלח/שלחי). O Syden não
// sabe o sexo de quem lê, e o masculino genérico, que muita interface usa, erra com metade das pessoas
// em toda frase.
//
// AS DUAS PORTAS, e elas são o que torna este arquivo possível:
//   1. O PASSADO da segunda pessoa se escreve IGUAL para os dois sem os sinais de vogal: שכחת é
//      shakhákhta e shakhákht. "Esqueceu a senha?" = שכחת את הסיסמה? — neutro na escrita.
//   2. O POSSESSIVO também: שלך, הסיסמה שלך, סיסמתך — a mesma grafia para os dois.
// (É a mesma propriedade do sufixo ـك do árabe, que lá passou batido. Aqui ela é usada de propósito.)
//
// O RESTO segue três regras:
//   - BOTÕES E AÇÕES no INFINITIVO (לשלוח, לשמור, לבטל), que não tem sexo e é o que as interfaces
//     em hebraico usam.
//   - Frases que falam com a pessoa vão pelo IMPESSOAL: אפשר ל… ("dá para…"), יש/אין ("há/não há"),
//     ou pelo PASSIVO no passado (נשלח, נמחק, הוזמנת), cujo sexo é o da COISA, não de quem lê.
//   - Nunca presente, futuro nem imperativo na segunda pessoa, e nenhum adjetivo sobre quem lê.
//
// Os NOMES DE CARGO (מנהל, חבר) ficam no masculino genérico, como rótulo de papel. "Dono" é בעלים,
