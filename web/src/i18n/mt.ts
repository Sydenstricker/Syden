// - O PLURAL (*jiktbu*, *qed jaraw*) não tem gênero, e foi usado à vontade.
// - "Min" (quem, genérico) leva o masculino gramatical, como em toda a língua ("min jidħol"): não é
//   ninguém em particular, e o MediaWiki faz igual.
// - Nomes de cargo ("Amministratur", "Membru", "Sid", "Lupu mannar", "Għarrief") são títulos, na forma
//   de dicionário. Onde o texto fala de QUEM LÊ, troquei o título por uma construção ("Como dono"
