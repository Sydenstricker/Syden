//
// A chave é o TEXTO EM PORTUGUÊS, exatamente como aparece no código. O que faltar aqui aparece em
// português, e não como tela vazia.
//
// ---------------------------------------------------------------------------------------------------
// Ș E Ț LEVAM VÍRGULA, NÃO CEDILHA — E ESTA É A ARMADILHA DESTE IDIOMA.
//
// O alfabeto romeno tem ș (U+0219) e ț (U+021B), com uma VÍRGULA embaixo. Existem dois sósias quase
// idênticos na tela, ş (U+015F) e ţ (U+0163), que são letras do TURCO, com cedilha. Durante anos o
// Windows usou os turcos no lugar dos romenos porque os certos não existiam nas fontes antigas, e
// por isso eles ainda aparecem copiados de todo canto da internet.
//
// Em corpo pequeno a diferença quase não se vê; para quem lê romeno, é texto escrito errado. Este
// arquivo tem ZERO cedilhas, e isso foi CONFERIDO contando os pontos de código, não olhando.
// ---------------------------------------------------------------------------------------------------
//
// O GÊNERO ESTÁ NO ADJETIVO, como no grego: "você está conectado" é conectat para um homem e
// conectată para uma mulher. O Syden não sabe o sexo de quem lê, então as frases descrevem a COISA e
// não a PESSOA — "Parola a fost schimbată" (a senha foi trocada) em vez de "você trocou". É a
// segunda língua seguida com esse mesmo desvio, e a saída é a mesma.
//
// O TRATAMENTO É `tu`, e aqui a regra do projeto vale sem ressalva. A divisão romena tu/dumneavoastră
// é a do tu/vous francês: `dumneavoastră` entre amigos soaria como cartório. Nos botões fica o
// imperativo singular (Alege, Trimite, Șterge), que é como qualquer aplicativo romeno fala.
//
// MEDIDO, não suposto, com `node -e` antes de traduzir:
//
//   Intl.NumberFormat('ro').format(1234567.5)  ->  1.234.567,5
//   Intl.PluralRules('ro')  ->  1 = "one";  0, 2, 5, 19 e 101 = "few";  20 = "other"
//   Intl.DisplayNames('ro', region)  ->  RO = România, MD = Republica Moldova, BR = Brazilia
//   Intl.RelativeTimeFormat('ro')  ->  -1 dia = ieri
//
// A SEGUNDA LINHA É A MAIS INTERESSANTE DA LISTA INTEIRA ATÉ AQUI: o romeno tem TRÊS categorias de
// plural, e a do meio é estranha a quem fala português — "few" vale para 0, para 2 a 19 e para
// qualquer número terminado em 01 a 19. É por isso que "193 de țări" leva um `de` que "5 ore" não
// leva: acima de 19, o substantivo entra com preposição. As frases deste arquivo seguem essa regra
// onde o número é fixo; onde ele é um campo {assim}, a forma escolhida é a que cabe nos dois casos.
//
// ESCRITA LATINA, logo ele entra no DETECTOR POR CHAVES de e2e/configuracoes-traduzidas.mjs, junto do
// vietnamita, do hauçá e do iorubá: não dá para achar português procurando letra estranha quando as
// letras são as mesmas. O que o romeno tem e o português não tem é ă, â, î, ș e ț; o que o português
// tem e o romeno não tem é ã, õ, ç, ê e ô — e é por aí que o teste separa um do outro.
//
